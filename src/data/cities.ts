const fold = (s: string) => s.normalize('NFD').replace(/\p{M}/gu, '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();

/** Recherche tolérante (accents, alias, préfixe) — pays d'abord si donné. */
export function findCities(query: string, country?: string, limit = 8): CityEntry[] {
  const q = fold(query);
  if (!q) return [];
  const score = (c: CityEntry): number => {
    const names = [c.name, ...(c.aliases ?? [])].map(fold);
    let best = 0;
    for (const n of names) {
      if (n === q) best = Math.max(best, 3);
      else if (n.startsWith(q)) best = Math.max(best, 2);
      else if (n.includes(q)) best = Math.max(best, 1);
    }
    if (best && country && c.country === country) best += 0.5;
    return best;
  };
  return CITIES
    .map((c) => ({ c, s: score(c) }))
    .filter((x) => x.s > 0)
    .sort((a, b) => b.s - a.s || a.c.name.localeCompare(b.c.name))
    .slice(0, limit)
    .map((x) => x.c);
}

/** Ville exacte (nom ou alias) dans un pays. */
export function findCity(name: string, country?: string): CityEntry | null {
  const q = fold(name);
  if (!q) return null;
  const hits = CITIES.filter((c) => [c.name, ...(c.aliases ?? [])].some((n) => fold(n) === q));
  return hits.find((c) => !country || c.country === country) ?? hits[0] ?? null;
}
